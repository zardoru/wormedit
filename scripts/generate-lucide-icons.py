#!/usr/bin/env python3
"""Rasterize the checked-in Lucide SVG subset into deterministic alpha masks."""

from io import BytesIO
from pathlib import Path
import subprocess

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/icons/lucide"
DESTINATION = ROOT / "src/ui/nuklear/lucide_icon_pixels.h"
SIZE = 40
NAMES = (
    "zoom-in", "zoom-out", "panel-right-open", "panel-right-close",
    "rotate-ccw", "paintbrush", "chevron-left", "chevron-right",
    "play", "pause", "square", "eye", "minus", "maximize",
    "minimize-2", "x", "audio-lines", "layers", "chevrons-left",
    "chevrons-right", "magnet", "metronome", "lock", "lock-open", "eye-off",
    "music-2",
)


def alpha_mask(name):
    png = subprocess.check_output(
        ["rsvg-convert", "-w", str(SIZE), "-h", str(SIZE), str(SOURCE / f"{name}.svg")]
    )
    image = Image.open(BytesIO(png)).convert("RGBA")
    if image.size != (SIZE, SIZE):
        raise ValueError(f"{name}: unexpected raster size {image.size}")
    return image.getchannel("A").tobytes()


def main():
    lines = [
        "// Generated by scripts/generate-lucide-icons.py from assets/icons/lucide.",
        "// See assets/icons/lucide/LICENSE for ISC and Feather MIT notices.",
        "#pragma once", "#include <array>", "#include <cstdint>",
        "namespace wormedit::ui::lucide::pixels {",
        f"inline constexpr int size = {SIZE};",
        f"inline constexpr std::array<std::array<std::uint8_t, {SIZE * SIZE}>, {len(NAMES)}> alpha{{{{",
    ]
    for name in NAMES:
        values = alpha_mask(name)
        lines.append(f"    // {name}")
        lines.append("    {{")
        for offset in range(0, len(values), 20):
            lines.append("        " + ", ".join(str(value) for value in values[offset:offset + 20]) + ",")
        lines.append("    }},")
    lines += ["}};", "} // namespace wormedit::ui::lucide::pixels", ""]
    DESTINATION.write_text("\n".join(lines))
    print(DESTINATION)


if __name__ == "__main__":
    main()
