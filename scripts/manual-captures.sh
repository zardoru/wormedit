#!/usr/bin/env bash
set -euo pipefail

# Captures the manual's screenshots in isolated Xvfb and stamps each with the commit it shows.
#   scripts/manual-captures.sh [shot ...]     capture every shot, or only the named ones
#   scripts/manual-captures.sh --check-stale  list shots whose UI code changed after their stamp
#
# A shot is docs/manual/shots/<id>.sh: a STEPS file for scripts/smoke-compose-virtual-x.sh.
# Its header names how the window starts:
#   # mode: landing|wizard|compose     (default compose)
#   # project: <path below the repository root>   (optional native project to open)
# The steps drive the window with click_at, xdotool and "$window_id"; the capture happens after
# them. The stamp is the short commit, with "+dirty" when UI sources had uncommitted changes. It is
# written into the PNG comment and into docs/manual/images/revisions.adoc as
# :shot-<id>-revision:, which the manual prints in each figure caption.
root_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
shots_dir="$root_dir/docs/manual/shots"
images_dir="$root_dir/docs/manual/images"
revisions="$images_dir/revisions.adoc"
ui_paths=(src/ui src/sys include/wormedit/core/interaction_state.h)

ui_revision() {
    local revision
    revision=$(git -C "$root_dir" rev-parse --short HEAD)
    if ! git -C "$root_dir" diff --quiet HEAD -- "${ui_paths[@]}"; then revision+="+dirty"; fi
    echo "$revision"
}

check_stale() {
    local stale=0 line id revision
    [[ -f $revisions ]] || { echo "No shots captured yet." >&2; return 1; }
    while IFS= read -r line; do
        [[ $line =~ ^:shot-(.+)-revision:\ (.+)$ ]] || continue
        id=${BASH_REMATCH[1]}
        revision=${BASH_REMATCH[2]%+dirty}
        if [[ ${BASH_REMATCH[2]} == *+dirty ]] ||
           ! git -C "$root_dir" diff --quiet "$revision" HEAD -- "${ui_paths[@]}"; then
            echo "stale: $id (captured at ${BASH_REMATCH[2]})"
            stale=1
        fi
    done < "$revisions"
    return "$stale"
}

header_value() {
    sed -n "s/^# $2: //p" "$1" | head -n 1
}

record_revision() {
    local id=$1 revision=$2 temp
    temp=$(mktemp)
    {
        echo "// Generated by scripts/manual-captures.sh: the commit each screenshot shows."
        if [[ -f $revisions ]]; then grep -v -e "^:shot-$id-revision:" -e '^//' "$revisions" || true; fi
        echo ":shot-$id-revision: $revision"
    } > "$temp"
    { head -n 1 "$temp"; tail -n +2 "$temp" | sort; } > "$revisions"
    rm -f "$temp"
}

capture() {
    local id=$1 shot="$shots_dir/$1.sh" mode project steps revision output
    [[ -f $shot ]] || { echo "No shot named $id ($shot)" >&2; return 1; }
    mode=$(header_value "$shot" mode); mode=${mode:-compose}
    project=$(header_value "$shot" project)
    revision=$(ui_revision)
    output="$images_dir/$id.png"
    steps=$(mktemp)
    # The wrapper ends with kill -9: an edited project would otherwise wait on its unsaved dialog.
    # Shots run in a 1600x900 window; their coordinates assume that size.
    printf '%s\nsource %q\nimport -window "$window_id" "$output"\nkill -9 "$app_pid" 2>/dev/null || true\n' \
        'xdotool windowsize --sync "$window_id" 1600 900; sleep 1.5' "$shot" > "$steps"
    WORMEDIT_SMOKE_SCREEN=1920x1080 STEPS="$steps" \
        "$root_dir/scripts/smoke-compose-virtual-x.sh" "$output" "$mode" \
        ${project:+"$root_dir/$project"} >/dev/null
    rm -f "$steps"
    mogrify -set comment "wormedit $revision" "$output"
    record_revision "$id" "$revision"
    echo "$id: $revision"
}

if [[ ${1:-} == --check-stale ]]; then
    check_stale
    exit
fi
mkdir -p "$images_dir"
if (($# == 0)); then
    for shot in "$shots_dir"/*.sh; do capture "$(basename "$shot" .sh)"; done
else
    for id in "$@"; do capture "$id"; done
fi
