// Prints the manual's generated AsciiDoc reference tables from the code that defines them, so the
// manual cannot drift from the shortcuts and layouts the editor ships with.
//   wormedit-manual-reference shortcuts   default command shortcuts, grouped by category
//   wormedit-manual-reference layouts     new-project layouts with lanes, lane keys and outputs
// documentation.manual_reference fails when docs/manual/generated/ differs from this output.

#include "sys/shortcut_rows.h"

#include <wormedit/core/command_registry.h>
#include <wormedit/core/lane_profiles.h>

#include <algorithm>
#include <array>
#include <cstdio>
#include <iostream>
#include <string>
#include <string_view>
#include <utility>
#include <vector>

namespace {
using namespace wormedit;

constexpr std::string_view generated_note =
    "// Generated by wormedit-manual-reference; do not edit. Regenerate with\n"
    "// `cmake --build build --target manual-reference`.\n";

constexpr std::array<std::pair<command_category_t, std::string_view>, 10> category_titles{{
    {command_category_t::document, "Project and charts"},
    {command_category_t::edit, "Editing"},
    {command_category_t::selection, "Selection"},
    {command_category_t::navigation, "Navigation"},
    {command_category_t::transport, "Playback"},
    {command_category_t::timing, "Timing"},
    {command_category_t::semantic_layer, "Layers"},
    {command_category_t::audio, "Sounds"},
    {command_category_t::workspace, "Workspace"},
    {command_category_t::tools, "Tools"},
}};

// Inline passthrough keeps "+" and "`" in key names literal.
auto keys_cell(const std::vector<shortcut_chord_t>& chords) -> std::string {
    if (chords.empty()) return "unbound";
    std::string text;
    for (const auto& chord : chords) {
        if (!text.empty()) text += ", ";
        text += "`+" + sys::shortcut_chord_text(chord, shortcut_primary_modifier_t::control) + "+`";
    }
    return text;
}

void print_shortcuts() {
    std::cout << generated_note;
    const auto registry = command_registry_t::from(nullptr);
    for (const auto& [category, title] : category_titles) {
        const auto in_category = [&](const command_t& command) {
            return command.definition.category == category;
        };
        if (std::ranges::none_of(registry.commands, in_category)) continue;
        std::cout << "\n." << title << "\n[cols=\"3,2\",options=\"header\"]\n|===\n"
                  << "|Command |Default keys\n";
        for (const auto& command : registry.commands) {
            if (!in_category(command)) continue;
            std::cout << "|" << command.definition.display_name << " |"
                      << keys_cell(command.definition.default_shortcuts) << "\n";
        }
        std::cout << "|===\n";
    }
}

auto lane_keys_cell(const lane_input_profile_t& profile) -> std::string {
    if (profile.input.bindings.empty()) return "none by default";
    auto lanes = profile.layout.lanes;
    std::ranges::sort(lanes, {}, &lane_definition_t::display_order);
    std::string text;
    for (const auto& lane : lanes) {
        const auto binding = std::ranges::find(profile.input.bindings, lane.id, &lane_binding_t::lane);
        const auto key = binding == profile.input.bindings.end() ? std::string{"·"}
            : sys::shortcut_chord_text({.key = static_cast<shortcut_key_t>(physical_key_hid_usage(binding->key))});
        if (!text.empty()) text += ' ';
        text += key;
    }
    return "`+" + text + "+`";
}

auto outputs_cell(const new_project_layout_descriptor_t& layout) -> std::string {
    std::string text;
    for (const auto& output : layout.default_output_groups) {
        if (!text.empty()) text += ", ";
        text += output.label;
    }
    return text;
}

void print_layouts() {
    std::cout << generated_note
              << "\n[cols=\"4,1,3,2\",options=\"header\"]\n|===\n"
              << "|Layout |Lanes |Default lane keys (left to right) |Default output groups\n";
    for (const auto& layout : new_project_layouts()) {
        const auto profile = layout.make_profile();
        std::cout << "|" << layout.label << " |" << profile.layout.lanes.size() << " |"
                  << lane_keys_cell(profile) << " |" << outputs_cell(layout) << "\n";
    }
    std::cout << "|===\n";
}
} // namespace

int main(int argc, char** argv) {
    const std::string_view kind = argc == 2 ? argv[1] : "";
    if (kind == "shortcuts") print_shortcuts();
    else if (kind == "layouts") print_layouts();
    else {
        std::fprintf(stderr, "usage: wormedit-manual-reference shortcuts|layouts\n");
        return 2;
    }
    return 0;
}
