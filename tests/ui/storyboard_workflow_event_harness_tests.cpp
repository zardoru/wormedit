    auto route(const std::vector<workspace_action_snapshot_t>& frames) -> storyboard_action_t {
        for (const auto& snapshot : frames) {
            const auto& action = snapshot.get().storyboard;
            if (action.kind == storyboard_action_kind_t::none || (action.kind == storyboard_action_kind_t::assets &&
                action.assets.kind == storyboard_assets_action_kind_t::set_thumbnail_demand)) continue;
            return dispatch(action);
        }
        return {};
    }
    auto click(std::string_view label) -> storyboard_action_t {
        CAPTURE(label);
        INFO(harness.drawn_text()); auto point = harness.drawn_text_center(label);
        if (!point) {
            for (const auto& text : harness.drawn_text_bounds()) {
                const auto start = text.text.find_first_not_of(' ');
                if (start != std::string::npos && std::string_view{text.text}.substr(start) == label)
                    point = {text.x + text.width / 2, text.y + text.height / 2};
            }
        }
        REQUIRE(point);
        return route(test::click_at(harness, point->first, point->second));
    }
    auto timeline_label(const storyboard_timeline_row_t& row) const -> std::pair<float, float> {
        const auto& drawn = harness.drawn_text_bounds();
        const auto found = std::ranges::find_if(drawn, [&](const auto& text) {
            return text.text.starts_with(row.track.node + " / ") && row.label.starts_with(text.text);
        });
        REQUIRE(found != drawn.end());
        // Renderer label lane is160px; text starts6px plus12px per depth inside
        // it. Use the lane centre, independent of the clipped glyph width.
        return {found->x - 6 - static_cast<float>(row.depth) * 12 + 80, found->y + found->height / 2};
    }
