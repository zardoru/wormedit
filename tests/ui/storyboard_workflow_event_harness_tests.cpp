constexpr std::string_view module = "scripts/visual-proof/long-generator-module.osbx.lua";
void show_generated(nuklear_event_harness_t& harness, bool owner_available = true) {
    REQUIRE(harness.ready());
    auto& view = harness.view(); view.active_tab = WORM_UI_WORKSPACE_TAB_STORYBOARD;
    view.compose.visible = false;
    auto& root = view.storyboard; root.visible = true;
    root.project = view.project_id; root.revision = view.document_revision; root.session_generation = 7;
    root.storyboards = {{.id = storyboard_id_t{11}, .name = "Generated proof", .kind = storyboard_kind_t::osbx,
        .generator_owned = true, .generator_recipe = owner_available ? std::optional{recipe_id_t{950}} : std::nullopt,
        .generator_module = std::string(module)}};
    root.refill_state({.selection = {.storyboard = storyboard_id_t{11}}});
    (void)harness.frame();
}
auto detach_points(const nuklear_event_harness_t& harness) -> std::vector<std::pair<float, float>> {
    std::vector<std::pair<float, float>> points;
    for (const auto& text : harness.drawn_text_bounds())
        if (text.text == "Detach") points.emplace_back(text.x + text.width / 2, text.y + text.height / 2);
    return points;
}
auto ownership_heading(const nuklear_event_harness_t& harness, std::pair<float, float> detach)
    -> const testing_drawn_text_view_t* {
    const testing_drawn_text_view_t* heading{};
    for (const auto& text : harness.drawn_text_bounds())
        if (text.text.starts_with("Generated by") && text.x < detach.first && text.y < detach.second &&
            (!heading || text.y > heading->y)) heading = &text;
    return heading;
}
auto banner_right(const nuklear_event_harness_t& harness, std::pair<float, float> detach, int width) -> float {
    const auto buttons = detach_points(harness);
    if (detach.second == std::ranges::max_element(buttons, {}, &std::pair<float, float>::second)->second)
        return static_cast<float>(width) - 12;
    const auto text = harness.drawn_text_bounds();
    const auto canvas = std::ranges::find_if(text, [](const auto& item) { return item.text.starts_with("Canvas "); });
    REQUIRE(canvas != text.end());
    return detach.first < canvas->x ? canvas->x - 12 : static_cast<float>(width) - 50;
}
void check_banner_line(const testing_drawn_text_view_t& text, float right) {
    CHECK(text.x >= 0);
    CHECK(text.x + text.width <= right);
}
void check_dock_banner(const nuklear_event_harness_t& harness, std::pair<float, float> detach, int width) {
    const auto* heading = ownership_heading(harness, detach);
    REQUIRE(heading);
    CHECK(heading->text.find("950") != std::string::npos);
    const auto right = banner_right(harness, detach, width); check_banner_line(*heading, right);
    std::string path;
    float bottom{};
    for (const auto& text : harness.drawn_text_bounds()) {
        if (text.y <= heading->y || text.y >= detach.second - 10 || std::abs(text.x - heading->x) > 1) continue;
        check_banner_line(text, right);
        path += text.text; bottom = text.y + text.height;
    }
    CHECK(path == module);
    CHECK(bottom < detach.second - 10);
}
